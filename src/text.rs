const GLYPH_WIDTH: u32 = 5; // Width in pixels of each glyph
const GLYPH_HEIGHT: u32 = 8; // Height in pixels of each glyph
const GLYPHS_PER_ROW: u32 = 20; // Number of characters per row in the font atlas

// Draw a character from the font atlas at the specified position
fn draw_char_index(index: u32, x: i32, y: i32) {
    let x_index = index % GLYPHS_PER_ROW;
    let y_index = index / GLYPHS_PER_ROW;

    blit_sub(
        &FONT,
        x,
        y,
        GLYPH_WIDTH,
        GLYPH_HEIGHT,
        GLYPH_WIDTH * x_index,
        GLYPH_HEIGHT * y_index,
        FONT_WIDTH,
        0,
    );
}

pub fn draw_char(char_string: char, x: i32, y: i32) {
    let ascii = char_string as i32 - 33;
    if ascii > 96 || ascii < 0 {
        return;
    }

    draw_char_index(ascii as u32, x, y);
}

pub fn draw_text(text: &str, mut x: i32, mut y: i32) {
    let start_x = x; // Save the starting x position
    for c in text.chars() {
        // if new line, reset x and increment y
        if c == '\n' {
            x = start_x;
            y += GLYPH_HEIGHT as i32;
            continue;
        }
        draw_char(c, x, y);
        x += GLYPH_WIDTH as i32;
    }
}
